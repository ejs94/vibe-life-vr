#!/usr/bin/env python3
"""Create, finish, and index standardized QA evidence runs.

Every run lives under ``out/qa/<gate>/runs/<timestamp>/``. A ``latest``
symlink points at the newest run, and ``out/qa/INDEX.md`` lists the newest
result for every gate. The manifest records the commit, working-tree state,
device mode, command, exit code, and artifact checksums so a human can tell
new evidence from old evidence without opening dozens of directories.
FINDING means the command ran and produced a diagnostic finding, not a pass;
INCONCLUSIVE means the result could not be determined.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import subprocess
import sys
from datetime import datetime
from pathlib import Path

REPO_DIR = Path(__file__).resolve().parent.parent
QA_ROOT = REPO_DIR / "out" / "qa"


def git_value(*args: str) -> str:
    try:
        return subprocess.check_output(
            ["git", *args], cwd=REPO_DIR, text=True, stderr=subprocess.DEVNULL
        ).strip()
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


def working_tree_dirty() -> bool:
    try:
        out = subprocess.check_output(
            ["git", "status", "--porcelain"],
            cwd=REPO_DIR,
            text=True,
            stderr=subprocess.DEVNULL,
        )
        return bool(out.strip())
    except (OSError, subprocess.CalledProcessError):
        return True


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def collect_artifacts(run_dir: Path) -> list[dict]:
    artifacts = []
    for path in sorted(run_dir.rglob("*")):
        if not path.is_file():
            continue
        if path.name in {"manifest.json", "result.json"}:
            continue
        artifacts.append(
            {
                "path": str(path.relative_to(run_dir)),
                "bytes": path.stat().st_size,
                "sha256": sha256_file(path),
            }
        )
    return artifacts


def write_json(path: Path, payload: dict) -> None:
    path.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n", encoding="utf-8")


def update_latest(gate_dir: Path, run_dir: Path) -> None:
    latest = gate_dir / "latest"
    if latest.is_symlink() or latest.exists():
        latest.unlink()
    latest.symlink_to(Path("runs") / run_dir.name, target_is_directory=True)


def rebuild_index() -> None:
    QA_ROOT.mkdir(parents=True, exist_ok=True)
    rows = []
    for gate_dir in sorted(QA_ROOT.iterdir()):
        if not gate_dir.is_dir() or not (gate_dir / "runs").is_dir():
            continue
        runs = sorted(
            (p for p in (gate_dir / "runs").iterdir() if p.is_dir()),
            key=lambda p: p.name,
            reverse=True,
        )
        for run_dir in runs:
            manifest_path = run_dir / "manifest.json"
            if not manifest_path.exists():
                continue
            manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
            commit = str(manifest.get("commit", "unknown"))
            rows.append(
                "| {gate} | {status} | {device} | {timestamp} | {commit} | {decision} | `{run}` |".format(
                    gate=manifest.get("gate", gate_dir.name),
                    status=manifest.get("status", "unknown"),
                    device=manifest.get("device", "pending"),
                    timestamp=manifest.get("timestamp", run_dir.name),
                    commit=commit[:12],
                    decision=manifest.get("human_decision", "PENDING"),
                    run=str(run_dir.relative_to(QA_ROOT)),
                )
            )
            break

    lines = [
        "# QA evidence index",
        "",
        "Generated by `scripts/qa_evidence.py`. Do not edit by hand.",
        "",
        "| Gate | Status | Device | Timestamp | Commit | Decision | Latest run |",
        "|---|---|---|---|---|---|---|",
    ]
    lines.extend(rows)
    lines.append("")
    (QA_ROOT / "INDEX.md").write_text("\n".join(lines), encoding="utf-8")


def command_new(args: argparse.Namespace) -> int:
    gate_dir = QA_ROOT / args.gate
    run_id = datetime.now().strftime("%Y%m%d_%H%M%S")
    run_dir = gate_dir / "runs" / run_id
    run_dir.mkdir(parents=True, exist_ok=True)
    manifest = {
        "gate": args.gate,
        "run_id": run_id,
        "timestamp": datetime.now().astimezone().isoformat(timespec="seconds"),
        "commit": git_value("rev-parse", "HEAD"),
        "branch": git_value("rev-parse", "--abbrev-ref", "HEAD"),
        "dirty": working_tree_dirty(),
        "device": args.device,
        "command": args.command,
        "exit_code": None,
        "status": "RUNNING",
        "human_decision": "PENDING",
        "artifacts": [],
        "notes": [],
    }
    write_json(run_dir / "manifest.json", manifest)
    update_latest(gate_dir, run_dir)
    rebuild_index()
    print(run_dir)
    return 0


def command_finish(args: argparse.Namespace) -> int:
    run_dir = Path(args.run).resolve()
    manifest_path = run_dir / "manifest.json"
    if not manifest_path.exists():
        print(f"manifest not found: {manifest_path}", file=sys.stderr)
        return 2
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    manifest["exit_code"] = args.exit_code
    manifest["status"] = args.status
    manifest["device"] = args.device
    if getattr(args, "human_decision", None) is not None:
        manifest["human_decision"] = args.human_decision
    else:
        manifest.setdefault("human_decision", "PENDING")
    if args.note:
        manifest["notes"].append(args.note)
    manifest["artifacts"] = collect_artifacts(run_dir)
    write_json(manifest_path, manifest)
    write_json(
        run_dir / "result.json",
        {
            "gate": manifest["gate"],
            "status": manifest["status"],
            "exit_code": manifest["exit_code"],
            "device": manifest["device"],
            "artifacts": manifest["artifacts"],
        },
    )
    gate_dir = run_dir.parent.parent
    update_latest(gate_dir, run_dir)
    rebuild_index()
    return 0


def command_index(_: argparse.Namespace) -> int:
    rebuild_index()
    print(QA_ROOT / "INDEX.md")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)

    new = sub.add_parser("new", help="create a new run and print its directory")
    new.add_argument("--gate", required=True)
    new.add_argument("--command", default="")
    new.add_argument("--device", default="pending", choices=["monado", "quest", "both", "pending"])
    new.set_defaults(func=command_new)

    finish = sub.add_parser("finish", help="record the result and artifact checksums")
    finish.add_argument("--run", required=True)
    finish.add_argument("--exit-code", type=int, required=True)
    finish.add_argument("--status", required=True, choices=["PASS", "FAIL", "INCONCLUSIVE", "FINDING"])
    finish.add_argument("--device", default="pending", choices=["monado", "quest", "both", "pending"])
    finish.add_argument("--human-decision", default=None, choices=["PENDING", "ADVANCE", "REWORK", "BLOCK"])
    finish.add_argument("--note", default="")
    finish.set_defaults(func=command_finish)

    index = sub.add_parser("index", help="rebuild out/qa/INDEX.md")
    index.set_defaults(func=command_index)

    args = parser.parse_args()
    return args.func(args)


if __name__ == "__main__":
    raise SystemExit(main())
